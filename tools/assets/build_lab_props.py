def triangles(node):
    return sum(len(s.tris) for s in node.geometry.values()) + sum(triangles(c) for c in node.children)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--list", action="store_true")
    args = parser.parse_args(argv)
    colors = palette()
    built = models()
    if args.list:
        for category, model in built:
            print(f"{category:13s} {model.root.name:30s} {triangles(model.root):6d} tris")
        return 0
    data = lib.load_sources()
    pack = lib.pack_by_id(data, "past_future_original")
    keep = [m for m in pack.get("derived_models", []) if m.get("generator") != "build_lab_props.py"]
    records = []
    for category, model in built:
        path = lib.MODELS / category / f"{model.root.name}.glb"
        path.parent.mkdir(parents=True, exist_ok=True)
        model.save(path, colors)
        records.append({"path": path.relative_to(lib.ENV).as_posix(), "source_member": f"build_lab_props.py:{model.root.name}",
                        "source_archive_sha256": None, "sha256": lib.sha256_file(path), "generator": "build_lab_props.py",
                        "converted_with": "tools/assets/meshkit.py", "date": lib.today(),
                        "changes": "Original procedural model; no third-party geometry."})
    pack["derived_models"] = keep + records
    lib.save_sources(data)
    print(f"wrote {len(records)} original models under {lib.MODELS.relative_to(lib.ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
