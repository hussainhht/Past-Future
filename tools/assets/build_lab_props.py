def palette():
    text = PALETTE.read_text(encoding="utf-8")
    return {slot: tuple(int(past[i:i + 2], 16) / 255 for i in (0, 2, 4))
            for slot, past, _future in re.findall(r'^\t"(\w+)": \["([0-9a-f]{6})", "([0-9a-f]{6})"\]', text, re.M)}


def face_z(shape):
    """Turn a +Y-facing flat shape so it faces +Z (for wall-mounted pieces)."""
    return shape.rotated(rx=90)


def lying(shape):
    """Turn a +Z-facing quad so it lies flat facing +Y, top edge toward -Z."""
    return shape.rotated(rx=-90)


def disc(r, n=24, uv=False):
    """Flat disc in the XY plane facing +Z, optional circular UVs for clock faces and labels."""
    pts = mk.circle(r, 0, n)[:, [0, 2]] * np.array([1, -1])
    tris, uvs = [], []
    for i in range(n):
        a, b = pts[i], pts[(i + 1) % n]
        tris.append([[0, 0, 0], [a[0], a[1], 0], [b[0], b[1], 0]])
        uvs.append([[0.5, 0.5], [0.5 + a[0] / (2 * r), 0.5 - a[1] / (2 * r)], [0.5 + b[0] / (2 * r), 0.5 - b[1] / (2 * r)]])
    return mk.Shape(tris, uvs if uv else None)


def rod(a, b, r=0.02, n=6):
    """A thin cylinder from point a to point b."""
    a, b = np.array(a, float), np.array(b, float)
    length = float(np.linalg.norm(b - a))
    shape = mk.cylinder(r, length, n)
    d = (b - a) / length
    pitch = math.degrees(math.acos(max(-1.0, min(1.0, d[1]))))
    yaw = math.degrees(math.atan2(d[0], d[2]))
    return shape.rotated(rx=pitch).rotated(ry=yaw).moved(*a)


def chain(points, r=0.025, n=5):
    return mk.merge(*[rod(points[i], points[i + 1], r, n) for i in range(len(points) - 1)])


