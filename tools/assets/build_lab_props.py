def wall_panel(name, width=MODULE, damaged=False, seed=0):
    """A wall module: origin at the bottom centre of the room-side face, wall behind (-Z)."""
    m = Model(name)
    r = m.root
    hw = width / 2
    if damaged:
        rng = np.random.default_rng(seed)
        jag = [(hw, WALL_H), (0.25 * hw, WALL_H)]
        for t in np.linspace(0.2, 0.95, 6):
            jag.append((0.25 * hw - t * 1.1 * hw + rng.uniform(-0.12, 0.12), WALL_H - t * 2.2 + rng.uniform(-0.15, 0.15)))
        outline = [(-hw, 0), (hw, 0)] + jag + [(-hw, 1.5)]
        r.add(mk.extrude(outline, WALL_T, z0=-WALL_T), "wall")
        r.add(mk.box(width - 0.1, WALL_H - 1.4, 0.05).moved(y=1.4, z=-WALL_T + 0.02), "rubber")
        for y in (2.1, 2.9, 3.5):
            r.add(rod((-hw + 0.1, y, -0.18), (hw - 0.1, y, -0.18), 0.06, 8), "steel" if y < 3 else "rust")
        r.add(chain([(-0.4, 3.6, -0.1), (-0.25, 2.8, 0.02), (-0.3, 2.2, 0.06), (-0.12, 1.75, 0.1)], 0.025), "cable_red")
        r.add(chain([(-0.6, 3.7, -0.12), (-0.62, 3.0, 0.0), (-0.48, 2.5, 0.08)], 0.025), "cable_blue")
        for k in range(3):
            x0, y0 = rng.uniform(-hw + 0.3, hw - 0.3), rng.uniform(0.4, 1.3)
            pts = [(x0, y0)]
            for _ in range(4):
                pts.append((pts[-1][0] + rng.uniform(-0.25, 0.25), pts[-1][1] + rng.uniform(0.1, 0.3)))
            for (xa, ya), (xb, yb) in zip(pts, pts[1:]):
                r.add(rod((xa, ya, 0.012), (xb, yb, 0.012), 0.012, 4), "rubber")
    else:
        r.add(mk.box(width, WALL_H, WALL_T).moved(z=-WALL_T / 2), "wall")
        for sx in (-1, 1):
            x = sx * (width / 4 + 0.05)
            r.add(mk.block(width / 2 - 0.42, 2.1, 0.045, 0.02).moved(x=x, y=1.6, z=0.02), "wall_panel")
            r.add(mk.box(width / 2 - 0.3, 0.05, 0.05).moved(x=x, y=3.72, z=0.025), "trim")
            r.add(mk.box(width / 2 - 0.3, 0.05, 0.05).moved(x=x, y=1.52, z=0.025), "trim")
    r.add(mk.block(width, 1.08, 0.05, 0.02).moved(y=0.2, z=0.025), "wall_dark")
    r.add(mk.block(width, 0.22, 0.07, 0.015).moved(z=0.035), "baseboard")
    r.add(mk.block(width, 0.08, 0.08, 0.015).moved(y=1.3, z=0.04), "trim")
    for sx in (-1, 1):
        r.add(mk.block(0.2, WALL_H - 0.2, 0.12, 0.02).moved(x=sx * (hw - 0.1), z=0.06), "wall_panel")
    if not damaged:
        r.add(mk.block(width, 0.2, 0.15, 0.03).moved(y=WALL_H - 0.2, z=0.075), "trim")
    else:
        r.add(mk.block(width * 0.35, 0.2, 0.15, 0.03).moved(x=hw - width * 0.175, y=WALL_H - 0.2, z=0.075), "trim")
    return m


